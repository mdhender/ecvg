// Package game reads and writes a game's data, kept as JSON files in the
// game's folder (by convention games/{code}): game.json holds the master data,
// stellia.json the Stellia, stars.json their stars, orbits.json the stars'
// orbits, planets.json the planets in those orbits,
// and races.json the races. The state that changes from turn to turn is kept
// for each turn in the folder turns/{turn}: deposits.json holds the planets'
// deposits, empires.json the empires, and colonies.json the empires' colonies.
// Games are generated by the ecgen command.
package game

import (
	"encoding/json/v2"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"

	"github.com/mdhender/ecvg/internal/cerrs"
)

// FileName is the name of the master data file in a game's folder.
const FileName = "game.json"

const (
	ErrGameExists   = cerrs.Error("game already exists")
	ErrInvalidCode  = cerrs.Error("invalid game code")
	ErrInvalidSeed  = cerrs.Error("invalid seed")
	ErrNotDirectory = cerrs.Error("not a directory")
	ErrTurnExists   = cerrs.Error("turn already exists")
)

// Game is a game's master data.
type Game struct {
	// Code identifies the game. It is the name of the game's folder.
	Code string `json:"code"`
	// Seed1 and Seed2 are the master seeds for prng.New.
	Seed1 Seed `json:"seed1"`
	Seed2 Seed `json:"seed2"`
	// Turn is the number of the game's current turn. A new game is at turn 0,
	// the players' setup turn. The game's state as of this turn is in the
	// folder TurnDir names.
	Turn int `json:"turn"`
}

// TurnsDirName is the name of the folder in a game's folder that holds one
// folder for each turn, named by the turn's number.
const TurnsDirName = "turns"

// TurnDir returns the folder that holds the state of the game in dir as of
// the turn numbered turn: dir/turns/{turn}.
func TurnDir(dir string, turn int) string {
	return filepath.Join(dir, TurnsDirName, strconv.Itoa(turn))
}

// Seed is a master seed. It is stored in JSON as a string of 16 lowercase
// hex digits, because JSON readers often hold numbers as float64, which
// cannot represent every uint64.
type Seed uint64

// MarshalText implements encoding.TextMarshaler.
func (s Seed) MarshalText() ([]byte, error) {
	return fmt.Appendf(nil, "%016x", uint64(s)), nil
}

// UnmarshalText implements encoding.TextUnmarshaler. It accepts only the
// form MarshalText writes.
func (s *Seed) UnmarshalText(text []byte) error {
	if len(text) != 16 {
		return fmt.Errorf("%w: %q: want 16 hex digits", ErrInvalidSeed, text)
	}
	v, err := strconv.ParseUint(string(text), 16, 64)
	if err != nil {
		return fmt.Errorf("%w: %q: want 16 hex digits", ErrInvalidSeed, text)
	}
	*s = Seed(v)
	return nil
}

// Data is all of a game's data.
type Data struct {
	Game     Game
	Stellia  []Stellium
	Stars    []Star
	Orbits   []Orbit
	Planets  []Planet
	Deposits []Deposit
	Races    []Race
	Empires  []Empire
	Colonies []Colony
	// OrderResults is what became of the orders given in the prior turn, in
	// empire ID and then line order. It is empty in the game's first turn.
	OrderResults []OrderResult
}

// Code returns the game code for the game folder dir: the folder's name. It
// fails if dir does not exist or is not a directory.
func Code(dir string) (string, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	sb, err := os.Stat(abs)
	if err != nil {
		return "", err
	} else if !sb.IsDir() {
		return "", fmt.Errorf("%s: %w", dir, ErrNotDirectory)
	}
	code := filepath.Base(abs)
	if code == string(filepath.Separator) || code == "." {
		return "", fmt.Errorf("%s: %w", dir, ErrInvalidCode)
	}
	return code, nil
}

type file struct {
	name string
	v    any
}

// files returns the game's files that don't change from turn to turn, which
// are in the game's folder.
func (d *Data) files() []file {
	return []file{
		{FileName, &d.Game},
		{StelliaFileName, &d.Stellia},
		{StarsFileName, &d.Stars},
		{OrbitsFileName, &d.Orbits},
		{PlanetsFileName, &d.Planets},
		{RacesFileName, &d.Races},
	}
}

// turnFiles returns the game's files that hold its state as of a turn, which
// are in that turn's folder.
func (d *Data) turnFiles() []file {
	return []file{
		{DepositsFileName, &d.Deposits},
		{EmpiresFileName, &d.Empires},
		{ColoniesFileName, &d.Colonies},
		{OrderResultsFileName, &d.OrderResults},
	}
}

// Write writes a new game's files into dir. Game.json, stellia.json,
// stars.json, orbits.json, planets.json, and races.json go in dir. The state
// as of the game's turn (deposits.json, empires.json, colonies.json, and
// order-results.json) goes
// in TurnDir(dir, d.Game.Turn).
//
// Dir must exist; Write creates only the turns folder and the turn's folder
// inside it. It fails with ErrGameExists if any of the files already exists,
// and it writes all of the files or none of them, removing any folder it
// created.
func (d Data) Write(dir string) error {
	turnDir := TurnDir(dir, d.Game.Turn)
	type out struct {
		path string
		data []byte
	}
	var outs []out
	add := func(dir string, files []file) error {
		for _, f := range files {
			// Marshal every file before writing any, so an error leaves none behind.
			data, err := json.Marshal(f.v)
			if err != nil {
				return fmt.Errorf("%s: %w", f.name, err)
			}
			outs = append(outs, out{filepath.Join(dir, f.name), append(data, '\n')})
		}
		return nil
	}
	if err := errors.Join(add(dir, d.files()), add(turnDir, d.turnFiles())); err != nil {
		return err
	}

	var created []string // files, then folders, in the order to remove them
	undo := func() {
		for _, path := range slices.Backward(created) {
			_ = os.Remove(path)
		}
	}
	for _, path := range []string{filepath.Dir(turnDir), turnDir} {
		if err := os.Mkdir(path, 0o755); err == nil {
			created = append(created, path)
		} else if !errors.Is(err, fs.ErrExist) {
			undo()
			return err
		}
	}
	for _, o := range outs {
		if err := writeNew(o.path, o.data); err != nil {
			undo()
			return err
		}
		created = append(created, o.path)
	}
	return nil
}

// WriteTurn saves the game's state as of its turn, d.Game.Turn, as a new turn
// of the game in dir: it writes deposits.json, empires.json, and colonies.json
// into TurnDir(dir, d.Game.Turn), then replaces game.json, which makes that
// turn the game's current turn. The files that don't change from turn to turn
// are left alone.
//
// It fails with ErrTurnExists if the turn's folder already exists. The folder
// is built under a temporary name and renamed into place, and game.json is
// replaced by renaming a temporary file, so a failure leaves the game as it
// was.
func (d Data) WriteTurn(dir string) error {
	turnDir := TurnDir(dir, d.Game.Turn)
	if _, err := os.Stat(turnDir); err == nil {
		return fmt.Errorf("%s: %w", turnDir, ErrTurnExists)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	gameJSON, err := json.Marshal(&d.Game)
	if err != nil {
		return fmt.Errorf("%s: %w", FileName, err)
	}

	tmp, err := os.MkdirTemp(filepath.Dir(turnDir), ".turn-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }() // a no-op once tmp is renamed
	for _, f := range d.turnFiles() {
		data, err := json.Marshal(f.v)
		if err != nil {
			return fmt.Errorf("%s: %w", f.name, err)
		}
		if err := writeNew(filepath.Join(tmp, f.name), append(data, '\n')); err != nil {
			return err
		}
	}
	if err := os.Chmod(tmp, 0o755); err != nil {
		return err
	}

	if err := os.Rename(tmp, turnDir); err != nil {
		return err
	}
	if err := replaceFile(filepath.Join(dir, FileName), append(gameJSON, '\n')); err != nil {
		_ = os.RemoveAll(turnDir)
		return err
	}
	return nil
}

// LoadData reads all of a game's files from dir: the files that don't change,
// then the state as of the game's current turn from its turn folder.
func LoadData(dir string) (Data, error) {
	var d Data
	for _, f := range d.files() {
		if err := loadJSON(dir, f.name, f.v); err != nil {
			return Data{}, err
		}
	}
	turnDir := TurnDir(dir, d.Game.Turn)
	for _, f := range d.turnFiles() {
		if err := loadJSON(turnDir, f.name, f.v); err != nil {
			return Data{}, err
		}
	}
	return d, nil
}

// writeNew writes data to a new file at path. It fails with ErrGameExists if
// path exists, and removes the file if writing fails.
func writeNew(path string, data []byte) error {
	fd, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("%s: %w", path, ErrGameExists)
	} else if err != nil {
		return err
	}
	if _, err = fd.Write(data); err == nil {
		err = fd.Sync()
	}
	if cerr := fd.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(path) // don't leave a partial file behind
		return err
	}
	return nil
}

// Load reads game.json from dir.
func Load(dir string) (Game, error) {
	var g Game
	if err := loadJSON(dir, FileName, &g); err != nil {
		return Game{}, err
	}
	return g, nil
}

// loadJSON reads the file name in dir into v, rejecting unknown members.
func loadJSON(dir, name string, v any) error {
	path := filepath.Join(dir, name)
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(data, v, json.RejectUnknownMembers(true)); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}
